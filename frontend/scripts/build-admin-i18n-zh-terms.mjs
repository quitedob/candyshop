/** @param {Locale} locale */
export function zhTermMap(locale) {
  const idx = locale === 'ja' ? 1 : 2
  return ZH_TERM_TRIPLES.slice().sort((a, b) => b[0].length - a[0].length).map(([zh, ja, ko]) => [zh, locale === 'ja' ? ja : ko])
}

/** @param {string} zh @param {Locale} locale */
export function translateZhTerms(zh, locale) {
  let result = zh
  for (const [from, to] of zhTermMap(locale)) {
    if (from && result.includes(from)) result = result.split(from).join(to)
  }
  return result
}

