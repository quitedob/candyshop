for (const loc of locales) {
  const file = `i18n/${loc}/customer.json`
  const data = JSON.parse(fs.readFileSync(file, 'utf8'))
  if (!data.customer.orders) data.customer.orders = {}
  Object.assign(data.customer.orders, patches[loc] || {})
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n', 'utf8')
  console.log('patched customer', loc)
}

for (const [loc, groups] of Object.entries(enumPatches)) {
  const file = `i18n/${loc}/common.json`
  const data = JSON.parse(fs.readFileSync(file, 'utf8'))
  for (const [group, values] of Object.entries(groups)) {
    data.enum[group] = { ...data.enum[group], ...values }
  }
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n', 'utf8')
  console.log('patched enum', loc)
}

