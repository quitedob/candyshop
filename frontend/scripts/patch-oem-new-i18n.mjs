for (const loc of locales) {
  const file = path.join(root, loc, 'customer.json')
  const data = JSON.parse(fs.readFileSync(file, 'utf8'))
  if (!data.customer?.oemProjects) {
    console.warn('skip', loc, 'no oemProjects')
    continue
  }

  if (fullOemProjects[loc]) {
    data.customer.oemProjects = { ...fullOemProjects[loc], ...extraKeys[loc] }
  } else {
    Object.assign(data.customer.oemProjects, extraKeys[loc])
  }

  fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n', 'utf8')
  console.log('patched', loc)
}

