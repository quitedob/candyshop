TOKEN_RE = re.compile(
    r"(\{[a-zA-Z0-9_]+\}|⌘K|Ctrl\+K|1200×630|aʷ|→|…|\.\.\.|&|[0-9]+(?:\.[0-9]+)?%?)"
)

PATH_OVERRIDES: dict[str, dict[str, str]] = {"id": {}, "ms": {}}


def _add(path: str, id_val: str, ms_val: str) -> None:
    PATH_OVERRIDES["id"][path] = id_val
    PATH_OVERRIDES["ms"][path] = ms_val


def flatten(obj: dict, prefix: str = "") -> dict[str, str]:
    out: dict[str, str] = {}
    for key, value in obj.items():
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            out.update(flatten(value, path))
        else:
            out[path] = value
    return out


def unflatten(flat: dict[str, str]) -> dict:
    root: dict = {}
    for path, value in flat.items():
        parts = path.split(".")
        cur = root
        for part in parts[:-1]:
            cur = cur.setdefault(part, {})
        cur[parts[-1]] = value
    return root


def protect(text: str) -> tuple[str, list[tuple[str, str]]]:
    replacements: list[tuple[str, str]] = []

    def repl(match: re.Match[str]) -> str:
        token = match.group(0)
        placeholder = f"__TOK{len(replacements)}__"
        replacements.append((placeholder, token))
        return placeholder

    return TOKEN_RE.sub(repl, text), replacements


def restore(text: str, replacements: list[tuple[str, str]]) -> str:
    for placeholder, original in replacements:
        text = text.replace(placeholder, original)
    return text


def is_mostly_english(text: str) -> bool:
    if not isinstance(text, str) or len(text) <= 2:
        return False
    if re.fullmatch(r"[\d\s.,\-+×→/:{}$#%&]+", text):
        return False
    latin = len(re.findall(r"[A-Za-z]", text))
    return latin / max(len(text), 1) > 0.55


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def save_json(path: Path, data: dict) -> None:
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def apply_lexicon(text: str, lexicon: dict[str, str]) -> str:
    protected, replacements = protect(text)
    result = protected
    for phrase, translation in sorted(lexicon.items(), key=lambda item: len(item[0]), reverse=True):
        if phrase in result:
            result = result.replace(phrase, translation)
    return restore(result, replacements)


def translate_text(text: str, locale: str) -> str:
    if text in EXACT_STRINGS.get(locale, {}):
        return EXACT_STRINGS[locale][text]
    lexicon = LEXICON_ID if locale == "id" else LEXICON_MS
    result = apply_lexicon(text, lexicon)
    for pattern, repl in PATTERNS.get(locale, []):
        result = re.sub(pattern, repl, result)
    return result


def build_locale(en_tree: dict, locale: str) -> dict:
    en_flat = flatten(en_tree)
    out_flat: dict[str, str] = {}
    overrides = PATH_OVERRIDES[locale]
    for path, en_val in en_flat.items():
        if path in overrides:
            out_flat[path] = overrides[path]
        else:
            out_flat[path] = translate_text(en_val, locale)
    return unflatten(out_flat)


def validate(en_tree: dict, locale_tree: dict, locale: str) -> dict:
    en_flat = flatten(en_tree)
    loc_flat = flatten(locale_tree)
    same = sum(1 for k in en_flat if en_flat[k] == loc_flat.get(k))
    priority_english: list[str] = []
    for path, en_val in en_flat.items():
        loc_val = loc_flat.get(path, en_val)
        if any(path.startswith(p) for p in PRIORITY_PREFIXES):
            if loc_val == en_val:
                priority_english.append(f"{path}: {loc_val}")
    return {
        "locale": locale,
        "leaf_count": len(en_flat),
        "same_as_en": same,
        "priority_english_leftovers": priority_english,
    }


